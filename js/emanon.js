/* ── Clock ── */
function initClock() {
  function tick() {
    const d = new Date();
    const p = n => String(n).padStart(2,'0');
    const clock = document.getElementById('clock');
    if (clock) {
      clock.textContent =
        `${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`;
    }
  }
  tick();
  setInterval(tick, 1000);
}

/* ── Panel Animations ── */
function initPanelAnimations() {
  document.addEventListener('DOMContentLoaded', function() {
    const panels = document.querySelectorAll('.panel');
    panels.forEach((panel, index) => {
      panel.style.animationDelay = `${index * 0.1}s`;
    });
  });
}

/* ── Title Animations ── */
let scrollInterval;
let marqueeStartTimer;

const cleanTitle = "emanon ✦ ";
const awayMarquee = "   come back. . . don't get lost - the signal is still here ✦   ";

function startMarquee(text, delay) {
  clearInterval(scrollInterval);
  let s = text;
  document.title = s;
  scrollInterval = setInterval(function () {
    s = s.substring(1) + s[0];
    document.title = s;
  }, delay);
}

function setCleanTitle() {
  clearInterval(scrollInterval);
  document.title = cleanTitle;
}

function handleVisibilityChange() {
  if (document.hidden) {
    startMarquee(awayMarquee, 50);
  } else {
    setCleanTitle();
  }
}

/* ── Init ── */
document.addEventListener('DOMContentLoaded', function() {
  initClock();
  initPanelAnimations();

  if (window === window.top) {
    setCleanTitle();
  }

  document.addEventListener("visibilitychange", handleVisibilityChange);
});

